"""Build the YOLO detection dataset from the BDD100K label index (run data/bdd100k_index.py first).

    python data/bdd100k_to_yolo.py                       # 20k train subset + full val, images as symlinks
    python data/bdd100k_to_yolo.py --train-size 70000    # all train images
    python data/bdd100k_to_yolo.py --copy                # real image copies (e.g. to upload to Colab)
    python data/bdd100k_to_yolo.py --no-oversample --out data/bdd100k/yolo_random   # random 20k baseline

Writes <out>/:
    images/{train,val}/<id>.jpg     symlinks to (or copies of) the original images
    labels/{train,val}/<id>.txt     YOLO labels
    val_day.txt, val_night.txt      val image lists for evaluating day and night separately
    bdd100k.yaml                    dataset config for Ultralytics (train, val, class names)
"""

from __future__ import annotations

import argparse
import shutil
from pathlib import Path

import pandas as pd

from perception.io.bdd100k_yolo import (
    CLASSES,
    RARE_CLASSES,
    clean_boxes,
    select_train_subset,
    yolo_label_lines,
)


def write_split(
    split: str, image_ids: list[str], boxes: pd.DataFrame, root: Path, out: Path, copy: bool
) -> int:
    img_dir = out / "images" / split
    lbl_dir = out / "labels" / split
    for d in (img_dir, lbl_dir):
        if d.exists():
            shutil.rmtree(d)
        d.mkdir(parents=True)

    by_image = dict(tuple(boxes.groupby("image_id", sort=False)))
    empty = boxes.iloc[:0]
    n_boxes = 0
    for image_id in image_ids:
        src = (root / "images" / "100k" / split / f"{image_id}.jpg").resolve()
        dst = img_dir / src.name
        if copy:
            shutil.copy2(src, dst)
        else:
            dst.symlink_to(src)
        lines = yolo_label_lines(by_image.get(image_id, empty))
        (lbl_dir / f"{image_id}.txt").write_text("\n".join(lines) + ("\n" if lines else ""))
        n_boxes += len(lines)
    return n_boxes


def main() -> None:
    parser = argparse.ArgumentParser(
        description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter
    )
    parser.add_argument("--root", type=Path, default=Path("data/bdd100k"))
    parser.add_argument("--out", type=Path, default=Path("data/bdd100k/yolo"))
    parser.add_argument("--train-size", type=int, default=20_000)
    parser.add_argument("--seed", type=int, default=0)
    parser.add_argument("--copy", action="store_true", help="copy images instead of symlinking")
    parser.add_argument(
        "--no-oversample", action="store_true", help="plain random train subset, no rare-class images first"
    )
    args = parser.parse_args()

    images = pd.read_parquet(args.root / "index" / "images.parquet")
    boxes = pd.read_parquet(args.root / "index" / "boxes.parquet")
    kept = clean_boxes(boxes)
    print(f"boxes: {len(boxes):,} -> {len(kept):,} after dropping other classes and boxes under 2 px")

    train_images = images[images.split == "train"]
    rare_classes = () if args.no_oversample else RARE_CLASSES
    train_ids = select_train_subset(
        train_images.image_id, kept[kept.split == "train"], args.train_size, rare_classes, seed=args.seed
    )
    val_images = images[images.split == "val"]
    val_ids = sorted(val_images.image_id)

    args.out.mkdir(parents=True, exist_ok=True)
    for split, ids in (("train", train_ids), ("val", val_ids)):
        n = write_split(split, ids, kept[kept.split == split], args.root, args.out, args.copy)
        print(f"{split}: {len(ids):,} images, {n:,} boxes")

    for tod, name in (("daytime", "day"), ("night", "night")):
        ids = sorted(val_images.loc[val_images.timeofday == tod, "image_id"])
        (args.out / f"val_{name}.txt").write_text("".join(f"./images/val/{i}.jpg\n" for i in ids))
        print(f"val_{name}.txt: {len(ids):,} images")

    names = "\n".join(f"  {i}: {name}" for i, name in enumerate(CLASSES))
    sampling = f"every image with {', '.join(rare_classes)} included" if rare_classes else "random sample"
    (args.out / "bdd100k.yaml").write_text(
        f"# Generated by data/bdd100k_to_yolo.py (train subset: {len(train_ids)} images, seed {args.seed},\n"
        f"# {sampling})\n"
        f"path: {args.out.resolve()}\ntrain: images/train\nval: images/val\nnames:\n{names}\n"
    )
    print(f"wrote {args.out}/bdd100k.yaml")


if __name__ == "__main__":
    main()
